#!/bin/bash
# Builds a release BorkHosts.app into build/ and signs it ad hoc (personal use, no Developer ID).
# Safe to run from any directory and to run repeatedly.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$root"

swift build -c release
bin="$(swift build -c release --show-bin-path)/BorkHosts"

app="$root/build/BorkHosts.app"
rm -rf "$app"
mkdir -p "$app/Contents/MacOS" "$app/Contents/Resources"
cp "$bin" "$app/Contents/MacOS/BorkHosts"
# The command-line tool for agents and scripts lives inside the app, so it always matches the app it talks to.
cp "$(dirname "$bin")/bork-hosts" "$app/Contents/MacOS/bork-hosts"
# Compile the layered icon (Resources/AppIcon.icon). actool writes Assets.car for macOS 26 and later, and AppIcon.icns
# for older versions. The artwork layer is generated by scripts/make-icon.sh and committed, so a build needs no image tools.
icons="$(mktemp -d)"
trap 'rm -rf "$icons"' EXIT
xcrun actool "$root/Resources/AppIcon.icon" --compile "$icons" --platform macosx --minimum-deployment-target 14.0 \
  --app-icon AppIcon --output-partial-info-plist "$icons/partial.plist" --target-device mac > "$icons/actool.log" 2>&1 \
  || { cat "$icons/actool.log" >&2; echo "actool failed to compile Resources/AppIcon.icon" >&2; exit 1; }
cp "$icons/Assets.car" "$icons/AppIcon.icns" "$app/Contents/Resources/"

cat > "$app/Contents/Info.plist" <<'PLIST'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleExecutable</key><string>BorkHosts</string>
    <key>CFBundleIconFile</key><string>AppIcon</string>
    <key>CFBundleIconName</key><string>AppIcon</string>
    <key>CFBundleIdentifier</key><string>com.borkweb.bork-hosts</string>
    <key>CFBundleName</key><string>bork-hosts</string>
    <key>CFBundlePackageType</key><string>APPL</string>
    <key>CFBundleShortVersionString</key><string>1.0</string>
    <key>CFBundleVersion</key><string>1</string>
    <key>LSMinimumSystemVersion</key><string>14.0</string>
    <key>NSPrincipalClass</key><string>NSApplication</string>
    <key>NSHighResolutionCapable</key><true/>
</dict>
</plist>
PLIST

codesign --force --sign - "$app"
echo "Built $app"
echo "Command-line tool: $app/Contents/MacOS/bork-hosts (link it into your PATH, for example: ln -sf \"$app/Contents/MacOS/bork-hosts\" ~/bin/bork-hosts)"
